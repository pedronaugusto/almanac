//! Writes `src/zone/windows.zig`: Windows' time zone names mapped to IANA names, from CLDR's
//! `windowsZones.xml` (each `mapZone` of territory 001, the name's default), sorted by Windows name.
const std = @import("std");

pub const Error = error{ Malformed, OutOfMemory };

const Pair = struct { windows: []const u8, iana: []const u8 };

fn attribute(element: []const u8, name: []const u8) ?[]const u8 {
    var needle: [32]u8 = undefined;
    const key = std.fmt.bufPrint(&needle, " {s}=\"", .{name}) catch return null;
    const at = std.mem.find(u8, element, key) orelse return null;
    const rest = element[at + key.len ..];
    const end = std.mem.findScalar(u8, rest, '"') orelse return null;
    return rest[0..end];
}

/// The Zig source of the table, for CLDR release `version`.
pub fn generate(gpa: std.mem.Allocator, xml: []const u8, version: []const u8) Error![]u8 {
    var pairs: std.ArrayList(Pair) = .empty;
    defer pairs.deinit(gpa);
    var rest = xml;
    while (std.mem.find(u8, rest, "<mapZone ")) |at| {
        const end = std.mem.findScalarPos(u8, rest, at, '>') orelse return error.Malformed;
        const element = rest[at..end];
        rest = rest[end..];
        const territory = attribute(element, "territory") orelse return error.Malformed;
        if (!std.mem.eql(u8, territory, "001")) continue;
        const windows = attribute(element, "other") orelse return error.Malformed;
        const iana = attribute(element, "type") orelse return error.Malformed;
        // The default is one name.
        if (std.mem.findScalar(u8, iana, ' ') != null) return error.Malformed;
        try pairs.append(gpa, .{ .windows = windows, .iana = iana });
    }
    std.mem.sort(Pair, pairs.items, {}, struct {
        fn less(_: void, a: Pair, b: Pair) bool {
            return std.mem.order(u8, a.windows, b.windows) == .lt;
        }
    }.less);
    var out: std.Io.Writer.Allocating = .init(gpa);
    defer out.deinit();
    const w = &out.writer;
    w.print(
        \\//! Windows' time zone names and the IANA zone each is by default (territory 001), from CLDR
        \\//! {s}'s windowsZones.xml (Unicode License v3: LICENSES/cldr-unicode-v3.txt). Generated by
        \\//! tools/windows.zig (`bay dev tzdb`); do not edit.
        \\
        \\pub const cldr_version = "{s}";
        \\
        \\pub const Pair = struct {{ windows: []const u8, iana: []const u8 }};
        \\
        \\/// Sorted by Windows name.
        \\pub const pairs = [_]Pair{{
        \\
    , .{ version, version }) catch return error.OutOfMemory;
    for (pairs.items) |p| w.print("    .{{ .windows = \"{s}\", .iana = \"{s}\" }},\n", .{ p.windows, p.iana }) catch return error.OutOfMemory;
    w.writeAll("};\n") catch return error.OutOfMemory;
    return out.toOwnedSlice();
}
